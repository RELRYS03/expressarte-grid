"""Local Expressarte administrator and optional vision analysis API.

Set EXPRESSARTE_ADMIN_PASSWORD_HASH to a scrypt hash generated by
`python admin_api.py hash-password`. Never commit the password or hash.
"""
import base64
import hashlib
import hmac
import json
import os
import secrets
import time
import urllib.error
import urllib.request
from http.cookies import SimpleCookie

ADMIN_EMAILS = {"relrysalves@gmail.com", "relrys17@gmail.com"}
SESSIONS = {}
ATTEMPTS = {}
MAX_BODY = 6 * 1024 * 1024


def password_hash(password):
    salt = secrets.token_bytes(16)
    key = hashlib.scrypt(password.encode(), salt=salt, n=16384, r=8, p=1)
    return "scrypt$" + base64.urlsafe_b64encode(salt + key).decode()


def password_valid(password, encoded):
    try:
        label, value = encoded.split("$", 1)
        if label != "scrypt":
            return False
        raw = base64.urlsafe_b64decode(value)
        key = hashlib.scrypt(password.encode(), salt=raw[:16], n=16384, r=8, p=1)
        return hmac.compare_digest(key, raw[16:])
    except (ValueError, TypeError):
        return False


def read_json(handler):
    size = int(handler.headers.get("Content-Length", 0))
    if size < 1 or size > MAX_BODY:
        raise ValueError("Tamanho da solicitação inválido.")
    return json.loads(handler.rfile.read(size))


def send_json(handler, status, value, cookie=None):
    body = json.dumps(value, ensure_ascii=False).encode()
    handler.send_response(status)
    handler.send_header("Content-Type", "application/json; charset=utf-8")
    handler.send_header("Cache-Control", "no-store")
    handler.send_header("X-Content-Type-Options", "nosniff")
    if cookie:
        handler.send_header("Set-Cookie", cookie)
    handler.send_header("Content-Length", str(len(body)))
    handler.end_headers()
    handler.wfile.write(body)


def session_email(handler):
    cookie = SimpleCookie()
    try:
        cookie.load(handler.headers.get("Cookie", ""))
        sid = cookie["expressarte_session"].value
    except (KeyError, ValueError):
        return None
    entry = SESSIONS.get(sid)
    if not entry or entry[1] < time.time():
        SESSIONS.pop(sid, None)
        return None
    return entry[0]


def same_origin(handler):
    origin = handler.headers.get("Origin")
    host = handler.headers.get("Host", "")
    return not origin or origin in ("http://" + host, "https://" + host)


def handle_get(handler):
    if handler.path != "/api/session":
        return False
    email = session_email(handler)
    send_json(handler, 200, {"authenticated": bool(email), "email": email})
    return True


def handle_post(handler):
    if handler.path not in ("/api/login", "/api/logout", "/api/vision"):
        return False
    if not same_origin(handler):
        send_json(handler, 403, {"error": "Origem não permitida."})
        return True
    try:
        data = read_json(handler)
    except (ValueError, json.JSONDecodeError):
        send_json(handler, 400, {"error": "Dados inválidos."})
        return True
    if handler.path == "/api/login":
        ip = handler.client_address[0]
        recent = [t for t in ATTEMPTS.get(ip, []) if time.time() - t < 900]
        if len(recent) >= 8:
            send_json(handler, 429, {"error": "Muitas tentativas. Aguarde 15 minutos."})
            return True
        email = str(data.get("email", "")).strip().lower()
        password = str(data.get("password", ""))
        encoded = os.environ.get("EXPRESSARTE_ADMIN_PASSWORD_HASH", "")
        if email not in ADMIN_EMAILS or not encoded or not password_valid(password, encoded):
            recent.append(time.time())
            ATTEMPTS[ip] = recent
            send_json(handler, 401, {"error": "E-mail ou senha inválidos."})
            return True
        ATTEMPTS.pop(ip, None)
        sid = secrets.token_urlsafe(32)
        SESSIONS[sid] = (email, time.time() + 12 * 3600)
        secure = "; Secure" if handler.headers.get("X-Forwarded-Proto") == "https" else ""
        send_json(handler, 200, {"email": email}, "expressarte_session=" + sid + "; HttpOnly; SameSite=Strict; Path=/; Max-Age=43200" + secure)
        return True
    if handler.path == "/api/logout":
        cookie = SimpleCookie()
        cookie.load(handler.headers.get("Cookie", ""))
        if "expressarte_session" in cookie:
            SESSIONS.pop(cookie["expressarte_session"].value, None)
        send_json(handler, 200, {"ok": True}, "expressarte_session=; HttpOnly; SameSite=Strict; Path=/; Max-Age=0")
        return True
    if not session_email(handler) and not data.get("key"):
        send_json(handler, 401, {"error": "Entre como administrador ou informe sua própria chave de API."})
        return True
    send_vision(handler, data)
    return True


def send_vision(handler, data):
    provider = data.get("provider")
    image = data.get("image", "")
    key = data.get("key") or os.environ.get("EXPRESSARTE_" + str(provider).upper() + "_API_KEY", "")
    if provider not in ("openai", "anthropic") or not isinstance(key, str) or not key:
        send_json(handler, 400, {"error": "Escolha um provedor e informe uma chave de API válida."})
        return
    if not isinstance(image, str) or len(image) > MAX_BODY or not image.startswith(("data:image/jpeg;base64,", "data:image/png;base64,", "data:image/webp;base64,")):
        send_json(handler, 400, {"error": "Envie uma foto PNG, JPEG ou WebP."})
        return
    prompt = ("Analise a foto da TRASEIRA de um celular. Devolva somente JSON com camera: "
              "{left, top, width, height}, cada número em porcentagem de 0 a 100 em relação ao RETÂNGULO DO CORPO do aparelho. "
              "A caixa deve envolver a ilha completa das câmeras e flash. Se não houver confiança, use null. "
              "Não invente dimensões físicas; a escala será dada pelo usuário.")
    try:
        if provider == "openai":
            url = "https://api.openai.com/v1/chat/completions"
            payload = {"model": "gpt-4o-mini", "response_format": {"type": "json_object"}, "messages": [{"role": "user", "content": [{"type": "text", "text": prompt}, {"type": "image_url", "image_url": {"url": image}}]}], "max_tokens": 300}
            headers = {"Authorization": "Bearer " + key}
        else:
            url = "https://api.anthropic.com/v1/messages"
            kind, encoded = image.split(";base64,", 1)
            payload = {"model": "claude-sonnet-4-5", "max_tokens": 300, "messages": [{"role": "user", "content": [{"type": "text", "text": prompt}, {"type": "image", "source": {"type": "base64", "media_type": kind[5:], "data": encoded}}]}]}
            headers = {"x-api-key": key, "anthropic-version": "2023-06-01"}
        req = urllib.request.Request(url, data=json.dumps(payload).encode(), headers={**headers, "Content-Type": "application/json"}, method="POST")
        with urllib.request.urlopen(req, timeout=35) as response:
            result = json.load(response)
        content = result["choices"][0]["message"]["content"] if provider == "openai" else result["content"][0]["text"]
        box = json.loads(content)["camera"]
        if not isinstance(box, dict) or any(not isinstance(box.get(k), (int, float)) for k in ("left", "top", "width", "height")) or not (0 <= box["left"] < 100 and 0 <= box["top"] < 100 and 0 < box["width"] <= 100 - box["left"] and 0 < box["height"] <= 100 - box["top"]):
            raise ValueError("A IA não encontrou um módulo de câmera confiável.")
        send_json(handler, 200, {"camera": box})
    except (urllib.error.URLError, KeyError, ValueError, json.JSONDecodeError) as exc:
        send_json(handler, 502, {"error": "A análise não pôde ser concluída. Confira a chave e tente marcar a câmera manualmente."})


